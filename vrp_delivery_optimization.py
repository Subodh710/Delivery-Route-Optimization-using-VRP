    widths(wc, [8, 13, 62, 18, 10, 12, 12, 11, 11, 11, 11, 9, 9, 44])

    # ---- Distance_Matrix (live haversine x circuity) ----------------------- #
    wd = wb.create_sheet("Distance_Matrix")
    put(wd, 1, 1, "Node", F_HEAD, fill=FILL_HEAD)
    for j in range(N + 1):
        put(wd, 1, 2 + j, j, F_HEAD, fill=FILL_HEAD, align=Alignment(horizontal="center"))
