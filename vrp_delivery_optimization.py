def _to_min(hhmm):
    h, m = str(hhmm).strip().split(":")
    return int(h) * 60 + int(m)


def _to_hhmm(minutes):
    return f"{int(minutes) // 60:02d}:{int(minutes) % 60:02d}"


def load_orders_csv(path):
    """Read raw orders. Required columns: address, demand_kg, service_min, tw_start, tw_end (HH:MM)."""
    df = pd.read_csv(path, dtype=str).fillna("")
    missing = [c for c in CSV_COLUMNS if c not in df.columns]
    if missing:
        raise ValueError(f"{path}: missing column(s) {missing}; expected {CSV_COLUMNS}")
    rows = []
    for i, r in df.iterrows():
        try:
            row = dict(raw=r["address"].strip(), demand=int(float(r["demand_kg"])),
                       service=int(float(r["service_min"])), tw_start=_to_min(r["tw_start"]),
                       tw_end=_to_min(r["tw_end"]))
        except ValueError as exc:
            raise ValueError(f"{path}: bad value on data row {i + 2}: {exc}") from exc
        if not row["raw"] or row["demand"] <= 0 or row["service"] < 0 or row["tw_start"] >= row["tw_end"]:
            raise ValueError(f"{path}: invalid order on data row {i + 2}: {dict(r)}")
        rows.append(row)
    return rows


