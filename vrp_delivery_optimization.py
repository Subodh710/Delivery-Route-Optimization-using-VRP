def haversine_km(lat1, lon1, lat2, lon2):
    p1, p2 = math.radians(lat1), math.radians(lat2)
    a = math.sin((p2 - p1) / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(math.radians(lon2 - lon1) / 2) ** 2
    return 6371.0 * 2 * math.asin(math.sqrt(a))


def distance_matrix(nodes, circuity):
    n = len(nodes)
    D = np.zeros((n, n))
    for i in range(n):
        for j in range(n):
            D[i, j] = circuity * haversine_km(nodes.lat[i], nodes.lon[i], nodes.lat[j], nodes.lon[j])
    return D


def baseline_nearest_neighbour(nodes, D, cap):
    """Capacity-aware nearest-neighbour; ignores time windows (common manual dispatch rule)."""
    unvisited = set(range(1, len(nodes)))
    routes = []
    while unvisited:
        cur, load, route = 0, 0, []
        while True:
            feas = [j for j in unvisited if load + nodes.demand_kg[j] <= cap]
            if not feas:
                break
            nxt = min(feas, key=lambda j: D[cur, j])
            route.append(nxt)
            load += nodes.demand_kg[nxt]
            unvisited.remove(nxt)
            cur = nxt
        routes.append(route)
    return routes


def solve_cvrptw(nodes, D, cfg):
    n = len(nodes)
    travel_min = np.ceil(D / cfg["speed_kmph"] * 60).astype(int)
    svc = nodes.service_min.astype(int).tolist()
    # arc cost in paise = fuel + driving-time cost
    arc = np.rint((D * cfg["fuel_per_km"] + D / cfg["speed_kmph"] * cfg["driver_per_hr"]) * 100).astype(int)
    manager = pywrapcp.RoutingIndexManager(n, cfg["fleet_size"], 0)
    routing = pywrapcp.RoutingModel(manager)

    def arc_cb(i, j):
        return int(arc[manager.IndexToNode(i), manager.IndexToNode(j)])
    routing.SetArcCostEvaluatorOfAllVehicles(routing.RegisterTransitCallback(arc_cb))
    for v in range(cfg["fleet_size"]):
        routing.SetFixedCostOfVehicle(int(cfg["fixed_per_vehicle"] * 100), v)

    def dem_cb(i):
        return int(nodes.demand_kg[manager.IndexToNode(i)])
    routing.AddDimensionWithVehicleCapacity(routing.RegisterUnaryTransitCallback(dem_cb), 0,
                                            [int(cfg["capacity_kg"])] * cfg["fleet_size"], True, "Load")

    def time_cb(i, j):
        a, b = manager.IndexToNode(i), manager.IndexToNode(j)
        return int(travel_min[a, b] + svc[a])
    routing.AddDimension(routing.RegisterTransitCallback(time_cb), 120, cfg["shift_end_min"], False, "Time")
    tdim = routing.GetDimensionOrDie("Time")
    for node in range(1, n):
        tdim.CumulVar(manager.NodeToIndex(node)).SetRange(int(nodes.tw_start[node]), int(nodes.tw_end[node]))
    for v in range(cfg["fleet_size"]):
        tdim.CumulVar(routing.Start(v)).SetRange(cfg["start_min"], cfg["start_min"])
        routing.AddVariableMinimizedByFinalizer(tdim.CumulVar(routing.End(v)))

    p = pywrapcp.DefaultRoutingSearchParameters()
    p.first_solution_strategy = routing_enums_pb2.FirstSolutionStrategy.PATH_CHEAPEST_ARC
    p.local_search_metaheuristic = routing_enums_pb2.LocalSearchMetaheuristic.GUIDED_LOCAL_SEARCH
    p.time_limit.seconds = int(cfg["solver_seconds"])
    sol = routing.SolveWithParameters(p)
    if sol is None:
        raise RuntimeError("OR-Tools found no feasible solution - relax time windows or add vehicles.")
    routes = []
    for v in range(cfg["fleet_size"]):
        idx, r = routing.Start(v), []
        while not routing.IsEnd(idx):
            nd = manager.IndexToNode(idx)
            if nd != 0:
                r.append(nd)
            idx = sol.Value(routing.NextVar(idx))
        if r:
            routes.append(r)
    return routes


