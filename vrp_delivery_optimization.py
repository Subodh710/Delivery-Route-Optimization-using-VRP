def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default="output")
    ap.add_argument("--solver-seconds", type=int, default=CFG["solver_seconds"])
    ap.add_argument("--reps", type=int, default=CFG["reps"])
    ap.add_argument("--seed", type=int, default=CFG["seed"])
    ap.add_argument("--online", action="store_true", help="use Nominatim for geocoding")
    ap.add_argument("--input-csv", help="raw orders CSV (columns: address, demand_kg, service_min, tw_start, tw_end)")
    ap.add_argument("--export-sample-csv", help="write the synthetic raw orders to this CSV and exit")
    ap.add_argument("--figures-dir", help="also save PNG figures to this folder")
    a = ap.parse_args()
    cfg = dict(CFG, solver_seconds=a.solver_seconds, reps=a.reps, seed=a.seed)
    os.makedirs(a.out_dir, exist_ok=True)

    if a.export_sample_csv:
        export_raw_csv(generate_raw_orders(cfg["seed"]), a.export_sample_csv)
        print("Wrote", a.export_sample_csv)
        return
    if a.input_csv:
        raw = load_orders_csv(a.input_csv)
        DATA_NOTE["assumptions"] = f"Customer orders loaded from {os.path.basename(a.input_csv)} (demand, service times and time windows as supplied)."
        DATA_NOTE["summary"] = "Geocodes are approximate (locality centroids) unless --online was used - verify before quoting savings."
    else:
        raw = generate_raw_orders(cfg["seed"])
    cleaned, log = clean_orders(raw)
    if not cleaned:
        raise SystemExit("No orders could be cleaned - check the address column and the locality list (GAZETTEER).")
    nodes = geocode_all(cleaned, cfg["seed"], a.online)
    too_big = nodes[nodes.demand_kg > cfg["capacity_kg"]]
    if len(too_big):
        raise SystemExit(f"Orders heavier than vehicle capacity ({cfg['capacity_kg']} kg): {too_big.customer_code.tolist()}")
    print(f"Raw rows: {len(raw)} | kept: {len(cleaned)} | duplicates dropped: "
          f"{sum(1 for e in log if e['status'].startswith('Dup'))} | rejected: "
          f"{sum(1 for e in log if e['status'].startswith('Rej'))}")
    print(f"Total demand {nodes.demand_kg.sum()} kg -> min vehicles {math.ceil(nodes.demand_kg.sum() / cfg['capacity_kg'])}")

    D = distance_matrix(nodes, cfg["circuity"])
    base = baseline_nearest_neighbour(nodes, D, cfg["capacity_kg"])
    opt = solve_cvrptw(nodes, D, cfg)
    eb, eo = evaluate_plan(base, nodes, D, cfg), evaluate_plan(opt, nodes, D, cfg)
    sb = simulate_plan(base, nodes, D, cfg, cfg["reps"], cfg["seed"])
    so = simulate_plan(opt, nodes, D, cfg, cfg["reps"], cfg["seed"] + 7)

    print("\nPLANNED  baseline :", {k: round(v, 1) for k, v in eb.items()})
    print("PLANNED  optimised:", {k: round(v, 1) for k, v in eo.items()})
    print("SIM mean cost  base/opt: %.0f / %.0f | late stops %.1f / %.1f" %
          (sb[:, 0].mean(), so[:, 0].mean(), sb[:, 2].mean(), so[:, 2].mean()))

    xlsx = os.path.join(a.out_dir, "VRP_Delivery_Optimization.xlsx")
    build_excel(xlsx, cfg, log, nodes, D, base, opt, sb, so,
                f"Guided Local Search, PATH_CHEAPEST_ARC start; objective = fuel + driving time + fixed cost per vehicle.")
    if a.figures_dir:
        save_figures(a.figures_dir, nodes, base, opt, eb, eo, sb, so, cfg["reps"])
        print("Wrote figures to", a.figures_dir)
    print("\nWrote", xlsx)


if __name__ == "__main__":
    main()
