def _typo(word, rng):
    if len(word) >= 7 and rng.random() < 0.20:
        i = rng.integers(2, len(word) - 2)
        return word[:i] + word[i + 1:]
    return word


def make_raw_address(rng, building, gaz):
    disp, side, pin, _, _ = gaz
    flat = rng.choice(["Flat {}", "FLAT NO {}", "{}", "Room {}", "Shop {}", "Office {}"]).format(
        int(rng.integers(101, 1204)))
    bld = f"{building} {rng.choice(SUFFIXES)}"
    street = rng.choice(STREETS)
    landmark = rng.choice(LANDMARKS)
    words = [_typo(w, rng) for w in disp.split()]
    loc = " ".join(words)
    if side:
        loc += rng.choice([f" ({side[0]})", f" {side}", f" {side[0]}", f"-{side}"])
    use_pin = rng.random() > 0.15
    if use_pin and rng.random() < 0.06:                       # occasionally a wrong pincode
        pin = rng.choice([g[2] for g in GAZETTEER])
    city = rng.choice([f"Mumbai {pin}", f"Mumbai - {pin[:3]} {pin[3:]}", f"MUMBAI, MAHARASHTRA {pin}",
                       f"Bombay {pin}"]) if use_pin else rng.choice(["Mumbai", "MUMBAI", "Mumbai, Maharashtra"])
    segs = [flat, bld, street, landmark, loc, city]
    segs = [s for s in segs if s]
    text = rng.choice([", ", " , ", ",  "]).join(segs)
    r = rng.random()
    return text.upper() if r < 0.30 else text.lower() if r < 0.45 else text


