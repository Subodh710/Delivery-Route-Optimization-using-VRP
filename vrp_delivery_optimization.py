def evaluate_plan(routes, nodes, D, cfg):
    tot = dict(vehicles=len(routes), km=0.0, drive_min=0.0, route_min=0.0, late_stops=0, late_min=0.0, cost=0.0)
    for r in routes:
        path = [0] + r + [0]
        t, km, drv, rmin = cfg["start_min"], 0.0, 0.0, 0.0
        late_s, late_m = 0, 0.0
        for a, b in zip(path[:-1], path[1:]):
            d = D[a, b]
            km += d
            dm = d / cfg["speed_kmph"] * 60
            drv += dm
            ready = t + dm
            start = max(ready, nodes.tw_start[b])
            lt = max(0.0, start - nodes.tw_end[b])
            if lt > 1e-9:
                late_s += 1
                late_m += lt
            t = start + nodes.service_min[b]
        rmin = t - cfg["start_min"]
        cost = km * cfg["fuel_per_km"] + rmin / 60 * cfg["driver_per_hr"] + cfg["fixed_per_vehicle"] \
            + late_m * cfg["late_penalty_per_min"]
        for k, v in dict(km=km, drive_min=drv, route_min=rmin, late_stops=late_s, late_min=late_m, cost=cost).items():
            tot[k] += v
    return tot


