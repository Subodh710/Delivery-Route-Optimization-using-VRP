def in_peak(t):
    return any(a <= t < b for a, b in PEAK_WINDOWS)


def simulate_plan(routes, nodes, D, cfg, reps, seed):
    rng = np.random.default_rng(seed)
    sig = cfg["travel_sigma"]
    out = np.zeros((reps, 5))   # cost, route_hours, late_stops, late_min, makespan_min
    tw_s, tw_e, svc = nodes.tw_start.values, nodes.tw_end.values, nodes.service_min.values
    for r_i in range(reps):
        cost = hours = lstops = lmin = mk = 0.0
        for route in routes:
            path = [0] + route + [0]
            t, km = cfg["start_min"], 0.0
            for a, b in zip(path[:-1], path[1:]):
                km += D[a, b]
                base = D[a, b] / cfg["speed_kmph"] * 60
                f = cfg["peak_factor"] if in_peak(t) else 1.0
                t += base * f * rng.lognormal(-sig ** 2 / 2, sig)
                t = max(t, tw_s[b])
                if t > tw_e[b]:
                    lstops += 1
                    lmin += t - tw_e[b]
                if b != 0:
                    t += svc[b] * rng.triangular(cfg["service_low"], 1.0, cfg["service_high"])
            hours += (t - cfg["start_min"]) / 60
            mk = max(mk, t)
            cost += km * cfg["fuel_per_km"] + (t - cfg["start_min"]) / 60 * cfg["driver_per_hr"] \
                + cfg["fixed_per_vehicle"]
        cost += lmin * cfg["late_penalty_per_min"]
        out[r_i] = [cost, hours, lstops, lmin, mk]
    return out


