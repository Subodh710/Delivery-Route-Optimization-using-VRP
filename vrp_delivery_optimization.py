ABBR = [(r"\bsoc\b\.?", "Society"), (r"\brd\b\.?", "Road"), (r"\bnr\b\.?", "Near"),
        (r"\bopp\b\.?", "Opposite"), (r"\bstn\b\.?", "Station"), (r"\bapt\b\.?", "Apartments"),
        (r"\bs v\b", "S V"), (r"\bflat no\b", "Flat"), (r"\bbldg\b\.?", "Building"), (r"\btwr\b\.?", "Tower")]
CITY_RE = re.compile(r"mumbai|bombay|maharashtra")
STREET_RE = re.compile(r"\b(road|rd|marg|lane|gali|stn|station|near|nr|opp|opposite|behind|next)\b")
PIN_RE = re.compile(r"\b(4\d{2})\s?(\d{3})\b")


def expand_abbr(seg):
    s = seg.lower()
    for pat, rep in ABBR:
        s = re.sub(pat, rep.lower(), s)
    s = re.sub(r"\s+", " ", s).strip()
    out = " ".join(w.upper() if w in ("chs", "s", "v", "mg", "lbs") else w.capitalize() for w in s.split(" "))
    return out.replace("Chs", "CHS")


def best_locality(segment):
    """Return (score, base_key, side_token) for the best fuzzy locality match in one segment."""
    t = segment.lower().replace("(e)", " east ").replace("(w)", " west ")
    toks = re.findall(r"[a-z]+", t)
    best = (0.0, None, None)
    cands = [(i, toks[i]) for i in range(len(toks))] + \
            [(i, toks[i] + toks[i + 1]) for i in range(len(toks) - 1)]
    for i, tok in cands:
        if len(tok) < 4:
            continue
        for base in BASES:
            sc = difflib.SequenceMatcher(None, tok, base).ratio()
            if sc >= 0.85 and sc >= best[0]:
                span = 2 if tok != toks[i] else 1
                side = toks[i + span] if i + span < len(toks) else None
                best = (sc, base, side)
    return best


def clean_orders(raw_rows):
    cleaned, seen, log = [], {}, []
    for rid, row in enumerate(raw_rows, start=1):
        raw = row["raw"]
        flags = []
        m = PIN_RE.search(raw)
        pin_raw = (m.group(1) + m.group(2)) if m else None
        text = PIN_RE.sub(" ", raw) if m else raw
        segs = [s.strip() for s in text.split(",") if s.strip()]
        # street / landmark segments (e.g. "Saki Naka Road") must not be mistaken for the locality
        scores = [(0.0, None, None) if STREET_RE.search(s.lower()) else best_locality(s) for s in segs]
        li = max(range(len(segs)), key=lambda i: (scores[i][0], i))
        sc, base, side_tok = scores[li]
        if base is None:
            log.append(dict(raw_id=rid, raw=raw, status="Rejected - locality not found", code="", clean="", flags=""))
            continue
        side = ""
        if side_tok in ("east", "e"):
            side = "east"
        elif side_tok in ("west", "w"):
            side = "west"
        gz = GAZ_BY_KEY.get((base, side))
        if gz is None:
            opts = [k for k in GAZ_BY_KEY if k[0] == base]
            gz = GAZ_BY_KEY[opts[0]]
            flags.append("side assumed" if len(opts) > 1 else "")
        disp, gside, gpin, lat, lon = gz
        if not pin_raw:
            flags.append("pincode imputed from locality")
        elif pin_raw != gpin:
            flags.append(f"pincode corrected {pin_raw}->{gpin}")
        locality = f"{disp} {gside}".strip()
        keep = [expand_abbr(s) for i, s in enumerate(segs)
                if i != li and not CITY_RE.search(s.lower()) and not re.fullmatch(r"[\d\s\-]+", s)]
        if sc < 0.999:
            flags.append("locality spelling fixed")
        clean_addr = ", ".join(keep + [locality, f"Mumbai - {gpin}"])
        bkey_words = [w for w in re.findall(r"[a-z]+", segs[1].lower()) if w not in STOP_WORDS] if len(segs) > 1 else []
        dkey = (" ".join(bkey_words), locality.lower())
        if dkey in seen:
            log.append(dict(raw_id=rid, raw=raw, status="Duplicate dropped", code=seen[dkey],
                            clean=clean_addr, flags="; ".join(f for f in flags if f)))
            continue
        code = f"C{len(cleaned) + 1:03d}"
        seen[dkey] = code
        if "tw_start" in row:                                   # explicit window (CSV input)
            tw = (row["tw_start"], row["tw_end"])
        else:                                                   # synthetic label
            tw = {"all": (540, 1080), "am": (540, 780), "pm": (780, 1080)}[row["tw"]]
        cleaned.append(dict(node_id=len(cleaned) + 1, customer_code=code, clean_address=clean_addr,
                            locality=locality, pincode=gpin, demand_kg=row["demand"],
                            service_min=row["service"], tw_start=tw[0], tw_end=tw[1],
                            _gaz_lat=lat, _gaz_lon=lon, _raw_id=rid))
        log.append(dict(raw_id=rid, raw=raw, status="Kept", code=code, clean=clean_addr,
                        flags="; ".join(f for f in flags if f)))
    return cleaned, log


