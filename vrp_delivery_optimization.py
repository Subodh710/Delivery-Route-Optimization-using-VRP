    wc = wb.create_sheet("Customers")
    heads = ["Node ID", "Customer code", "Clean address", "Locality", "Pincode", "Latitude", "Longitude",
             "Demand (kg)", "Service (min)", "TW start (min)", "TW end (min)", "TW start", "TW end", "Geocode method"]
