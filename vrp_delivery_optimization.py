FILL_KEY = PatternFill("solid", fgColor="FFF2CC")
FILL_TOT = PatternFill("solid", fgColor="D9E1F2")
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def put(ws, r, c, v, font=F_BASE, fmt=None, fill=None, border=True, align=None):
    cell = ws.cell(r, c, v)
    cell.font = font
    if fmt:
        cell.number_format = fmt
    if fill:
        cell.fill = fill
    if border:
        cell.border = BORDER
    if align:
        cell.alignment = align
    return cell


def header(ws, r, labels, c0=1):
    for i, h in enumerate(labels):
        put(ws, r, c0 + i, h, F_HEAD, fill=FILL_HEAD,
            align=Alignment(horizontal="center", vertical="center", wrap_text=True))
    ws.row_dimensions[r].height = 32


def widths(ws, ws_widths):
    for i, w in enumerate(ws_widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w


